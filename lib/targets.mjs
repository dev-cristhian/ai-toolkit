// Tool-specific knowledge: where agents and MCP configs live, and the
// file format each tool expects. Verified against the official docs of
// Claude Code, Cursor, OpenAI Codex and VS Code + GitHub Copilot (2026-11).
import { homedir } from 'node:os';
import { join } from 'node:path';
import { parseFrontmatter, stripFrontmatterKey } from './frontmatter.mjs';

const home = () => homedir();
const codexHome = () => process.env.CODEX_HOME || join(home(), '.codex');
const copilotHome = () => process.env.COPILOT_HOME || join(home(), '.copilot');

// ---------------------------------------------------------------------------
// Agents
// ---------------------------------------------------------------------------

/** Destination file for an agent, per target and scope. */
export function agentPath(target, scope, id, cwd = process.cwd()) {
  const global = scope === 'global';
  switch (target) {
    case 'claude': return join(global ? join(home(), '.claude') : join(cwd, '.claude'), 'agents', `${id}.md`);
    case 'cursor': return join(global ? join(home(), '.cursor') : join(cwd, '.cursor'), 'agents', `${id}.md`);
    case 'codex': return join(global ? codexHome() : join(cwd, '.codex'), 'agents', `${id}.toml`);
    case 'copilot': return global
      ? join(copilotHome(), 'agents', `${id}.agent.md`)
      : join(cwd, '.github', 'agents', `${id}.agent.md`);
    default: throw new Error(`Unknown target: ${target}`);
  }
}

function tomlBasicString(value) {
  return JSON.stringify(value);
}

function tomlMultiline(value) {
  if (!value.includes("'''")) return `'''\n${value}\n'''`;
  return `"""\n${value.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"')}\n"""`;
}

/** Convert a Markdown agent (YAML frontmatter + prompt) to the target format. */
export function renderAgent(target, sourceText) {
  // Hub-only metadata is not meant for the tools; drop it from the copy.
  const cleaned = stripFrontmatterKey(sourceText.replace(/\r\n/g, '\n'), 'metadata');
  if (target !== 'codex') return cleaned;
  const { data, body } = parseFrontmatter(cleaned);
  return [
    '# Generated by ai-toolkit from a Markdown agent definition.',
    `name = ${tomlBasicString(data.name)}`,
    `description = ${tomlBasicString(data.description)}`,
    `developer_instructions = ${tomlMultiline(body.trim())}`,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// MCP servers
// ---------------------------------------------------------------------------

function authEnvValue(server) {
  const env = server.auth?.env;
  return env && process.env[env] ? process.env[env] : null;
}

/** Description of where/how an MCP server is registered for a target. */
export function mcpPlan(target, scope, server, cwd = process.cwd()) {
  const global = scope === 'global';
  const hasKey = Boolean(authEnvValue(server));
  const env = server.auth?.env;

  switch (target) {
    case 'claude': {
      const args = ['mcp', 'add', '--scope', global ? 'user' : 'project'];
      if (server.transport === 'http') {
        args.push('--transport', 'http');
        // Claude Code stores headers literally; never write a secret into a project file.
        if (hasKey && global) args.push('--header', `Authorization: Bearer ${authEnvValue(server)}`);
        args.push(server.name, server.url);
      } else {
        args.push(server.name, '--', server.command, ...(server.args ?? []));
      }
      const notes = [];
      if (server.auth && hasKey && global) notes.push(`${env} value will be stored in ~/.claude.json.`);
      if (server.auth && hasKey && !global) notes.push(`${env} is not written to the project .mcp.json; add the header manually if needed.`);
      return { kind: 'cli', cli: 'claude', args, checkArgs: ['mcp', 'get', server.name], notes,
        display: `claude ${args.map((a) => (a.startsWith('Authorization:') ? '"Authorization: Bearer ***"' : a)).join(' ')}` };
    }
    case 'cursor': {
      const file = join(global ? join(home(), '.cursor') : join(cwd, '.cursor'), 'mcp.json');
      const entry = server.transport === 'http'
        ? { url: server.url, ...(hasKey ? { headers: { Authorization: `Bearer \${env:${env}}` } } : {}) }
        : { command: server.command, args: server.args ?? [] };
      return { kind: 'json', file, rootKey: 'mcpServers', name: server.name, entry };
    }
    case 'copilot': {
      if (global) {
        // Portable Copilot format (recommended "Copilot Global" destination in VS Code).
        const file = join(copilotHome(), 'mcp-config.json');
        const entry = server.transport === 'http'
          ? { type: 'http', url: server.url, ...(hasKey ? { headers: { Authorization: `Bearer \${${env}}` } } : {}) }
          : { command: server.command, args: server.args ?? [] };
        return { kind: 'json', file, rootKey: 'mcpServers', name: server.name, entry };
      }
      const file = join(cwd, '.vscode', 'mcp.json');
      const entry = server.transport === 'http'
        ? { type: 'http', url: server.url, ...(hasKey ? { headers: { Authorization: `Bearer \${env:${env}}` } } : {}) }
        : { type: 'stdio', command: server.command, args: server.args ?? [] };
      return { kind: 'json', file, rootKey: 'servers', name: server.name, entry };
    }
    case 'codex': {
      const file = join(global ? codexHome() : join(cwd, '.codex'), 'config.toml');
      const lines = [`[mcp_servers.${server.name}]`];
      if (server.transport === 'http') {
        lines.push(`url = ${tomlBasicString(server.url)}`);
        if (hasKey) lines.push(`bearer_token_env_var = ${tomlBasicString(env)}`);
      } else {
        lines.push(`command = ${tomlBasicString(server.command)}`);
        lines.push(`args = [${(server.args ?? []).map(tomlBasicString).join(', ')}]`);
      }
      return { kind: 'toml', file, name: server.name, block: lines.join('\n') };
    }
    default:
      throw new Error(`Unknown target: ${target}`);
  }
}

/** True when a TOML document already declares [mcp_servers.<name>]. */
export function tomlHasServer(text, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`^\\s*\\[mcp_servers\\.(?:"${escaped}"|'${escaped}'|${escaped})\\]\\s*$`, 'm').test(text);
}
